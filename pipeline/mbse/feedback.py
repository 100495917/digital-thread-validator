"""Runtime feedback loop for requirement thresholds.

The feedback stage reads the observed p95 latency of the status endpoint,
compares it with the threshold declared by a performance requirement, writes a
deterministic report, and optionally opens or updates a GitHub issue through the
``gh`` CLI.  Issue handling is best effort: every public helper degrades to a
``skipped`` result instead of raising.
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path
from typing import Any

from .loaders import LoadError, load_requirements

REPORT_DIRECTORY = Path("build") / "reports"
FEEDBACK_JSON = REPORT_DIRECTORY / "feedback.json"

DEFAULT_REQUIREMENT_ID = "REQ-013"
DEFAULT_THRESHOLD_MS = 100.0

_GH_TIMEOUT_SECONDS = 30
_THRESHOLD_PATTERN = re.compile(
    r"under\s+([0-9]+(?:\.[0-9]+)?)\s*(ms|milliseconds?|s|seconds?)\b",
    re.IGNORECASE,
)


def _format_number(value: float) -> str:
    """Format a numeric threshold without a trailing ``.0`` when integral."""
    return f"{value:g}"


def requirement_threshold_ms(
    root: Path = Path("."),
    requirement_id: str = DEFAULT_REQUIREMENT_ID,
) -> float:
    """Return the latency threshold declared by ``requirement_id`` in ms.

    The requirement text is scanned for a phrase such as ``under 100 ms``.
    A missing requirement or missing/unsupported phrase falls back to
    :data:`DEFAULT_THRESHOLD_MS` so the feedback loop remains runnable.
    """
    root = Path(root)
    try:
        requirements = load_requirements(root)
    except LoadError:
        return DEFAULT_THRESHOLD_MS

    for requirement in requirements:
        if requirement.id != requirement_id:
            continue
        match = _THRESHOLD_PATTERN.search(requirement.text)
        if match is None:
            return DEFAULT_THRESHOLD_MS
        amount = float(match.group(1))
        unit = match.group(2).lower()
        if unit.startswith("s") and not unit.startswith("ms"):
            amount *= 1000.0
        return round(amount, 3)
    return DEFAULT_THRESHOLD_MS


def evaluate_feedback(
    observed_p95_ms: float,
    threshold_ms: float,
    requirement_id: str = DEFAULT_REQUIREMENT_ID,
) -> dict[str, Any]:
    """Compare an observed p95 latency with a requirement threshold."""
    observed = round(float(observed_p95_ms), 3)
    threshold = round(float(threshold_ms), 3)
    delta = round(observed - threshold, 3)
    return {
        "requirement_id": requirement_id,
        "observed_p95_ms": observed,
        "threshold_ms": threshold,
        "status": "violated" if observed > threshold else "ok",
        "delta_ms": delta,
    }


def write_feedback(report: dict[str, Any], root: Path = Path(".")) -> Path:
    """Write ``report`` to ``build/reports/feedback.json`` under ``root``."""
    root = Path(root)
    path = root / FEEDBACK_JSON
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    return path


def _run_gh(arguments: list[str], root: Path) -> tuple[str | None, str]:
    """Run ``gh`` and return ``(stdout, error)``; both empty on success."""
    try:
        completed = subprocess.run(
            ["gh", *arguments],
            cwd=root,
            capture_output=True,
            text=True,
            timeout=_GH_TIMEOUT_SECONDS,
            check=False,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        return None, "gh CLI unavailable: " + " ".join(str(exc).split())
    if completed.returncode != 0:
        detail = (completed.stderr or completed.stdout or "").strip()
        detail = " ".join(detail.split())[:200] or f"exit status {completed.returncode}"
        return None, detail
    return completed.stdout or "", ""


def _issue_title(report: dict[str, Any]) -> str:
    observed = _format_number(float(report.get("observed_p95_ms", 0.0)))
    threshold = _format_number(float(report.get("threshold_ms", 0.0)))
    return (
        f"[{report.get('requirement_id', DEFAULT_REQUIREMENT_ID)}] "
        f"Performance threshold violated: p95 {observed} ms > {threshold} ms"
    )


def _issue_body(report: dict[str, Any]) -> str:
    requirement_id = report.get("requirement_id", DEFAULT_REQUIREMENT_ID)
    return "\n".join(
        [
            f"Requirement `{requirement_id}` has a performance threshold violation.",
            "",
            f"- Observed p95: {_format_number(float(report.get('observed_p95_ms', 0.0)))} ms",
            f"- Threshold: {_format_number(float(report.get('threshold_ms', 0.0)))} ms",
            f"- Delta: {_format_number(float(report.get('delta_ms', 0.0)))} ms",
            "",
            "Generated by the digital-thread feedback loop.",
        ]
    )


def _parse_issue_numbers(stdout: str) -> list[int]:
    """Return issue numbers from ``gh issue list --json number`` output."""
    try:
        payload = json.loads(stdout or "[]")
    except json.JSONDecodeError:
        return []
    if not isinstance(payload, list):
        return []
    numbers: list[int] = []
    for entry in payload:
        if isinstance(entry, dict):
            try:
                numbers.append(int(entry.get("number")))
            except (TypeError, ValueError):
                continue
    return numbers


def open_or_update_issue(
    report: dict[str, Any],
    root: Path = Path("."),
) -> dict[str, str]:
    """Open or update a GitHub issue for a violated requirement.

    Only ``status == "violated"`` reports produce an issue.  Every failure path
    returns ``{"action": "skipped", "reason": ...}``; this helper never raises.
    """
    try:
        if report.get("status") != "violated":
            return {"action": "skipped", "reason": "requirement is satisfied"}

        requirement_id = str(report.get("requirement_id", DEFAULT_REQUIREMENT_ID))
        search = f"{requirement_id} in:title,body"
        stdout, error = _run_gh(
            [
                "issue",
                "list",
                "--search",
                search,
                "--state",
                "open",
                "--limit",
                "1",
                "--json",
                "number",
            ],
            Path(root),
        )
        if stdout is None:
            return {"action": "skipped", "reason": error or "gh issue list failed"}

        numbers = _parse_issue_numbers(stdout)
        title = _issue_title(report)
        body = _issue_body(report)

        if numbers:
            number = numbers[0]
            output, error = _run_gh(
                ["issue", "comment", str(number), "--body", body],
                Path(root),
            )
            if output is None:
                return {
                    "action": "skipped",
                    "reason": error or f"gh issue comment failed for #{number}",
                }
            return {"action": "updated", "reason": f"commented on issue #{number}"}

        output, error = _run_gh(
            ["issue", "create", "--title", title, "--body", body],
            Path(root),
        )
        if output is None:
            return {"action": "skipped", "reason": error or "gh issue create failed"}
        reference = " ".join(output.split())
        reason = f"created issue: {reference}" if reference else "created issue"
        return {"action": "created", "reason": reason}
    except Exception as exc:  # noqa: BLE001 - feedback must never break a pipeline
        return {"action": "skipped", "reason": " ".join(str(exc).split())}
